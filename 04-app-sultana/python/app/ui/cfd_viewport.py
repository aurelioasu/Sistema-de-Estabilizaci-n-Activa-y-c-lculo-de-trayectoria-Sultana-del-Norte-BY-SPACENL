    @staticmethod
    def _flow_reference(field: object) -> tuple[np.ndarray, float]:
        """Estimate the true freestream direction and speed from OpenFOAM U."""
        vectors = np.asarray(field.point_data["U"], dtype=float)
        finite = vectors[np.all(np.isfinite(vectors), axis=1)]
        if not len(finite):
            return np.array((-1.0, 0.0, 0.0)), 1.0
        direction = np.nanmedian(finite, axis=0)
        speed = float(np.linalg.norm(direction))
        if speed <= 1e-9:
            return np.array((-1.0, 0.0, 0.0)), 1.0
        return direction / speed, speed

    def _streamline_seed_cloud(self, field: object, *, compact: bool = False) -> object:
        """Place a circular rake immediately upstream of the physical rocket."""
        direction, _speed = self._flow_reference(field)
        basis_u, basis_v = self._basis(direction)
        centre = -direction * (0.5 * PHYSICAL_BODY_LENGTH_M + 0.17)
        rings = ((0.052, 10), (0.088, 14), (0.135, 18)) if compact else (
            (0.055, 10), (0.095, 14), (0.145, 18), (0.205, 22),
        )
        points: list[np.ndarray] = []
        for radius, count in rings:
            for angle in np.linspace(0.0, 2.0 * math.pi, count, endpoint=False):
                points.append(centre + basis_u * (radius * math.cos(angle)) + basis_v * (radius * math.sin(angle)))
        return self._pv.PolyData(np.asarray(points))

    def _scalar_feature_seed_cloud(self, field: object, scalar: str, *, count: int = 48) -> object:
        """Seed real high-gradient wake regions instead of the uniform inlet plane."""
        points = np.asarray(field.points, dtype=float)
        values = np.asarray(field.point_data[scalar], dtype=float)
        velocity = np.asarray(field.point_data["U"], dtype=float)
        speed = np.linalg.norm(velocity, axis=1)
        x0, x1, y0, y1, z0, z1 = self._FLOW_VIEW_BOUNDS
        radial = np.linalg.norm(points[:, 1:3], axis=1)
        finite = np.all(np.isfinite(points), axis=1) & np.isfinite(values) & np.isfinite(speed)
        near_body_and_wake = (
            (points[:, 0] >= max(x0, -0.90)) & (points[:, 0] <= min(x1, 0.58)) &
            (points[:, 1] >= y0) & (points[:, 1] <= y1) &
            (points[:, 2] >= z0) & (points[:, 2] <= z1) &
            (radial >= 0.035) & (radial <= 0.34) & (speed >= 0.25)
        )
        candidates = np.flatnonzero(finite & near_body_and_wake)
        if not len(candidates):
            return self._streamline_seed_cloud(field, compact=True)
        threshold = float(np.nanpercentile(values[candidates], 70.0))
        candidates = candidates[values[candidates] >= threshold]
        order = candidates[np.argsort(values[candidates])[::-1]][:6000]
        selected: list[int] = []
        minimum_spacing = 0.034
        for index in order:
            point = points[index]
            if not selected or np.min(np.linalg.norm(points[np.asarray(selected)] - point, axis=1)) >= minimum_spacing:
                selected.append(int(index))
                if len(selected) >= count:
                    break
        if len(selected) < min(12, count):
            selected = [int(index) for index in order[:count]]
        return self._pv.PolyData(points[np.asarray(selected, dtype=int)])

    def _wake_seed_cloud(self, field: object) -> object:
        """Place two compact circular rakes immediately behind the rocket."""
        direction, _speed = self._flow_reference(field)
        basis_u, basis_v = self._basis(direction)
        points: list[np.ndarray] = []
        for axial_distance in (0.50 * PHYSICAL_BODY_LENGTH_M + 0.03,
                               0.50 * PHYSICAL_BODY_LENGTH_M + 0.13):
            centre = direction * axial_distance
            for radius, count in ((0.050, 12), (0.095, 16), (0.155, 20)):
                for angle in np.linspace(0.0, 2.0 * math.pi, count, endpoint=False):
                    points.append(
                        centre + basis_u * (radius * math.cos(angle)) +
                        basis_v * (radius * math.sin(angle))
                    )
        return self._pv.PolyData(np.asarray(points))

    def _render_velocity_plane(self, field: object, clim: tuple[float, float]) -> None:
        """Add one contour plane behind the body, leaving the rocket unobstructed."""
        try:
            plane = field.slice(normal=(0.0, 1.0, 0.0), origin=(0.0, 0.16, 0.0))
            plane = plane.clip_box((-0.78, 0.88, 0.159, 0.161, -0.25, 0.25), invert=False)
            if not plane.n_points:
                return
            vectors = np.asarray(plane.point_data["U"], dtype=float)
            plane.point_data["velocity_mps"] = np.linalg.norm(vectors, axis=1)
            self._plotter.add_mesh(
                plane, scalars="velocity_mps", cmap="turbo", clim=clim, opacity=0.17,
                lighting=False, name="cfd-velocity-plane", show_scalar_bar=False,
                reset_camera=False,
            )
            self._streamline_names.append("cfd-velocity-plane")
        except (KeyError, TypeError, ValueError):
            return

    @staticmethod
    def _ranked_streamline_cells(lines: object, scalar: str, max_count: int) -> list[int]:
        """Prefer curved/high-gradient paths near the vehicle over uniform far-field lines."""
        connectivity = np.asarray(lines.lines, dtype=int)
        points = np.asarray(lines.points, dtype=float)
        values = np.asarray(lines.point_data[scalar], dtype=float)
        position = 0
        rows: list[tuple[int, float, float, float, float, float, float]] = []
        for cell_index in range(int(lines.n_cells)):
            count = int(connectivity[position])
            ids = connectivity[position + 1:position + 1 + count]
            position += count + 1
            if count < 3:
                continue
            path = points[ids]
            path_values = values[ids]
            radial_min = float(np.min(np.linalg.norm(path[:, 1:3], axis=1)))
            lateral_displacement = float(np.linalg.norm(path[-1, 1:3] - path[0, 1:3]))
            scalar_peak = float(np.nanpercentile(np.abs(path_values), 92.0))
            scalar_span = float(np.nanpercentile(path_values, 95.0) - np.nanpercentile(path_values, 5.0))
            segments = np.diff(path, axis=0)
            lengths = np.linalg.norm(segments, axis=1)
            valid = lengths > 1e-9
            unit = segments[valid] / lengths[valid, None]
            turning = (
                float(np.sum(np.arccos(np.clip(np.sum(unit[1:] * unit[:-1], axis=1), -1.0, 1.0))))
                if len(unit) > 1 else 0.0
            )
            path_length = float(np.sum(lengths))
            chord = float(np.linalg.norm(path[-1] - path[0]))
            loop_ratio = min(path_length / max(chord, 0.025), 8.0)
            rows.append((
                cell_index, radial_min, lateral_displacement, scalar_peak, abs(scalar_span), turning, loop_ratio,
            ))
        if not rows:
            return []
        peak_scale = max(row[3] for row in rows) or 1.0
        span_scale = max(row[4] for row in rows) or 1.0
        turning_scale = max(row[5] for row in rows) or 1.0
        if scalar == "vorticity_1ps":
            scored = [
                (
                    2.0 * row[3] / peak_scale + 1.2 * row[4] / span_scale +
                    2.8 * row[5] / turning_scale + 2.0 * min(row[6] / 2.5, 1.0) +
                    1.5 * max(0.0, 1.0 - row[1] / 0.20),
                    row[0],
                )
                for row in rows
            ]
            return [cell for _score, cell in sorted(scored, reverse=True)[:max_count]]
        peak_weight = 0.25 if scalar == "velocity_mps" else 2.0
        scored = [
            (
                peak_weight * row[3] / peak_scale + 2.3 * row[4] / span_scale +
                2.1 * min(row[2] / 0.18, 1.0) + 1.4 * max(0.0, 1.0 - row[1] / 0.18),
                row[0],
            )
            for row in rows
        ]
        return [cell for _score, cell in sorted(scored, reverse=True)[:max_count]]

    def _integrated_pathlines(
        self, field: object, scalar: str, *, max_count: int, compact: bool = False,
        feature_seeded: bool = False,
    ) -> object | None:
        """Integrate and retain only actual OpenFOAM paths that interact with the rocket."""
        vortex_vectors = next((name for name in ("vorticity", "curlU") if name in field.point_data), None)
        is_vortex_line = feature_seeded and scalar == "vorticity_1ps" and vortex_vectors is not None
        if is_vortex_line:
            seeds = self._scalar_feature_seed_cloud(field, scalar)
            vector_name = str(vortex_vectors)
            integration_direction = "both"
            max_length = 0.85
        elif feature_seeded:
            seeds = self._wake_seed_cloud(field)
            vector_name = "U"
            integration_direction = "forward"
            max_length = 1.30
        else:
            seeds = self._streamline_seed_cloud(field, compact=compact)
            vector_name = "U"
            integration_direction = "forward"
            max_length = 2.0
        lines = field.streamlines_from_source(
            seeds, vectors=vector_name, integration_direction=integration_direction,
            max_length=max_length,
            initial_step_length=0.004, max_steps=2400, compute_vorticity=False,
        )
        if not lines.n_points or scalar not in lines.point_data:
            return None
        selected = self._ranked_streamline_cells(lines, scalar, max_count)
        if not selected:
            return None
        view_bounds = (-0.78, 0.72, -0.30, 0.30, -0.30, 0.30) if is_vortex_line else self._FLOW_VIEW_BOUNDS
        retained = lines.extract_cells(selected).extract_surface(algorithm="dataset_surface").clip_box(
            view_bounds, invert=False
        ).extract_surface(algorithm="dataset_surface")
        retained.field_data["trajectory_count"] = np.asarray([len(selected)], dtype=np.int32)
        return retained

    @staticmethod
    def _trajectory_count(lines: object) -> int:
        values = lines.field_data.get("trajectory_count")
        return int(np.asarray(values).ravel()[0]) if values is not None and len(values) else int(lines.n_cells)

    def _add_pathline_arrows(
        self, lines: object, *, scalar: str, clim: tuple[float, float], cmap: str,
        actor_name: str, log_scale: bool = False, max_glyphs: int | None = None,
        arrow_scale: float | None = None,
    ) -> None:
        """Add sparse directional glyphs without hiding the integrated trajectories."""
        vector_name = next(
            (name for name in ("vorticity", "curlU") if scalar == "vorticity_1ps" and name in lines.point_data),
            "U",
        )
        if vector_name not in lines.point_data or scalar not in lines.point_data or lines.n_points < 2:
            return
        points = np.asarray(lines.points, dtype=float)
        vectors = np.asarray(lines.point_data[vector_name], dtype=float)
        values = np.asarray(lines.point_data[scalar], dtype=float)
        finite = np.all(np.isfinite(points), axis=1) & np.all(np.isfinite(vectors), axis=1) & np.isfinite(values)
        candidates = np.flatnonzero(finite)
        if not len(candidates):
            return
        glyph_limit = max_glyphs if max_glyphs is not None else (72 if scalar == "vorticity_1ps" else 150)
        chosen = candidates[np.linspace(0, len(candidates) - 1, min(glyph_limit, len(candidates)), dtype=int)]
        direction = vectors[chosen]
        magnitude = np.linalg.norm(direction, axis=1)
        valid = magnitude > 1e-9
        if not np.any(valid):
            return
        cloud = self._pv.PolyData(points[chosen][valid])
        cloud["flow_direction"] = direction[valid] / magnitude[valid, None]
        cloud[scalar] = values[chosen][valid]
        arrow = self._pv.Arrow(tip_length=0.50, tip_radius=0.18, shaft_radius=0.060)
        glyphs = cloud.glyph(
            orient="flow_direction", scale=False,
            factor=arrow_scale if arrow_scale is not None else (0.045 if scalar == "vorticity_1ps" else 0.032),
            geom=arrow,
        )
        self._plotter.add_mesh(
            glyphs, scalars=scalar, cmap=cmap, clim=clim, log_scale=log_scale,
            opacity=0.90, name=actor_name, show_scalar_bar=False, reset_camera=False,
        )

    def _add_vortex_rotation_rings(self, field: object) -> None:
        """Render compact local rotation indicators from exported vorticity vectors.

        A ring is a vorticity glyph: its plane is normal to the local curl(U),
        its arrow follows the measured rotation direction, and its colour comes
        from the local vorticity magnitude.  It is deliberately not presented
        as a streamline.
        """
        vector_name = next((name for name in ("vorticity", "curlU") if name in field.point_data), None)
        if vector_name is None:
            return
        points = np.asarray(field.points, dtype=float)
        vectors = np.asarray(field.point_data[vector_name], dtype=float)
        magnitude = np.linalg.norm(vectors, axis=1)
        radial = np.linalg.norm(points[:, 1:3], axis=1)
        finite = np.all(np.isfinite(points), axis=1) & np.all(np.isfinite(vectors), axis=1)
        nearby = (
            (points[:, 0] >= -0.62) & (points[:, 0] <= 0.55) &
            (radial >= 0.035) & (radial <= 0.29) & (magnitude > 1e-9)
        )
        candidates = np.flatnonzero(finite & nearby)
        if not len(candidates):
            return
        cutoff = float(np.nanpercentile(magnitude[candidates], 86.0))
        ordered = candidates[magnitude[candidates] >= cutoff]
        ordered = ordered[np.argsort(magnitude[ordered])[::-1]][:4000]
        selected: list[int] = []
        for index in ordered:
            if not selected or np.min(np.linalg.norm(points[np.asarray(selected)] - points[index], axis=1)) >= 0.115:
                selected.append(int(index))
                if len(selected) == 6:
                    break
        if not selected:
            return
        chosen = np.asarray(selected, dtype=int)
        values = magnitude[chosen]
        positive = magnitude[np.isfinite(magnitude) & (magnitude > 0.0)]
        clim = (
            max(float(np.nanpercentile(positive, 5.0)), 1e-12),
            max(float(np.nanpercentile(positive, 97.0)), 1e-11),
        )
        normalised = (values - float(np.min(values))) / max(float(np.ptp(values)), 1e-12)
        ring_points: list[np.ndarray] = []
        ring_lines: list[np.ndarray] = []
        ring_values: list[np.ndarray] = []
        arrow_points: list[np.ndarray] = []
        arrow_vectors: list[np.ndarray] = []
        arrow_values: list[float] = []
        offset = 0
        angles = np.linspace(0.0, 2.0 * math.pi, 49)
        for index, value, relative in zip(chosen, values, normalised):
            axis = vectors[index] / max(float(magnitude[index]), 1e-12)
            first, second = self._basis(axis)
            centre = points[index].copy()
            radial_direction = np.array((0.0, centre[1], centre[2]))
            radial_length = float(np.linalg.norm(radial_direction))
            if radial_length > 1e-9:
                centre += 0.020 * radial_direction / radial_length
            radius = 0.045 + 0.030 * float(relative)
            circle = np.asarray([
                centre + radius * (math.cos(angle) * first + math.sin(angle) * second)
                for angle in angles
            ])
            ring_points.append(circle)
            ring_lines.append(np.concatenate(([len(circle)], np.arange(offset, offset + len(circle), dtype=int))))
            ring_values.append(np.full(len(circle), value, dtype=float))
            arrow_angle = 5.25
            arrow_points.append(centre + radius * (math.cos(arrow_angle) * first + math.sin(arrow_angle) * second))
            arrow_vectors.append(-math.sin(arrow_angle) * first + math.cos(arrow_angle) * second)
            arrow_values.append(float(value))
            offset += len(circle)
        rings = self._pv.PolyData(np.vstack(ring_points))
        rings.lines = np.concatenate(ring_lines)
        rings["vorticity_1ps"] = np.concatenate(ring_values)
        tubes = rings.tube(radius=0.0032, n_sides=10)
        self._plotter.add_mesh(
            tubes, scalars="vorticity_1ps", cmap="viridis", clim=clim, log_scale=True,
            opacity=0.94, smooth_shading=True, ambient=0.24, specular=0.50, specular_power=24,
            name="cfd-vortex-rings", show_scalar_bar=True,
            scalar_bar_args=self._scalar_bar("Vorticidad (1/s)"), reset_camera=False,
        )
        self._vortex_names.append("cfd-vortex-rings")
        arrows = self._pv.PolyData(np.asarray(arrow_points))
        arrows["rotation_direction"] = np.asarray(arrow_vectors)
        arrows["vorticity_1ps"] = np.asarray(arrow_values)
        glyphs = arrows.glyph(
            orient="rotation_direction", scale=False, factor=0.036,
            geom=self._pv.Arrow(tip_length=0.50, tip_radius=0.20, shaft_radius=0.065),
        )
        self._plotter.add_mesh(
            glyphs, scalars="vorticity_1ps", cmap="viridis", clim=clim, log_scale=True,
            opacity=0.98, name="cfd-vortex-ring-arrows", show_scalar_bar=False, reset_camera=False,
        )
        self._vortex_names.append("cfd-vortex-ring-arrows")
        self._plotter.add_text(
            f"ANILLOS DE VORTICIDAD · OPENFOAM\n{len(chosen)} zonas de rotación local · "
            f"{clim[0]:.3g}–{clim[1]:.3g} 1/s\nAnillo y flecha = sentido local de curl(U)",
            name="cfd-mode-info", position="upper_left", font_size=9, color="#17212b",
        )

    def _render_surface_fields(self, frame: object) -> None:
        """Render only the selected wall quantity from the exported surface."""
        surface_path = _frame_value(frame, "surface_vtk_path")
        if not self._plotter or not surface_path or not Path(surface_path).is_file():
            return
        try:
            surface = self._pv.read(surface_path)
            arrays = set(surface.array_names)
            pressure = next((name for name in ("p", "p_rgh", "pressure_pa") if name in arrays), None)
            if pressure and self._cfd_layer == "pressure":
                density = 1.0 if pressure == "pressure_pa" else float(getattr(self._cfd_result, "air_density_kg_m3", 1.225))
                values = np.asarray(surface[pressure], dtype=float) * density
                surface["pressure_pa"] = values
                clim = robust_scalar_range(values, symmetric=True)
                self._plotter.add_mesh(
                    surface, scalars="pressure_pa", cmap="coolwarm", clim=clim, opacity=1.0,
                    n_colors=14, smooth_shading=False, show_edges=False,
                    name="cfd-pressure-surface", show_scalar_bar=True,
                    scalar_bar_args=self._scalar_bar("Presión manométrica (Pa)"), reset_camera=False,
                )
                self._plotter.add_text(
                    f"PRESIÓN SOBRE LA SUPERFICIE\nRango robusto: {clim[0]:.3g} a {clim[1]:.3g} Pa\n"
                    "Rojo = sobrepresión · azul = succión",
                    name="cfd-mode-info", position="upper_left", font_size=9, color="#17212b",
                )
            shear = next((name for name in ("wallShearStress", "wallShear", "tauWall") if name in arrays), None)
            if shear and self._cfd_layer == "friction":
                source = surface if shear in surface.point_data else surface.cell_data_to_point_data(pass_cell_data=False)
                vector = np.asarray(source.point_data[shear], dtype=float)
                points = np.asarray(source.points)
                magnitude = np.linalg.norm(vector, axis=1)
                clim = robust_scalar_range(magnitude, lower=1.0, upper=99.0)
                source.point_data["wall_shear_pa"] = magnitude
                self._plotter.add_mesh(
                    source, scalars="wall_shear_pa", cmap="inferno", clim=clim, opacity=0.94,
                    n_colors=24, smooth_shading=True, show_edges=False,
                    name="cfd-wall-shear-surface", show_scalar_bar=True,
                    scalar_bar_args=self._scalar_bar("Esfuerzo cortante (Pa)"), reset_camera=False,
                )
                threshold = float(np.nanpercentile(magnitude, 45.0))
                candidates = np.flatnonzero(magnitude >= threshold)
                selected = candidates[np.linspace(0, len(candidates) - 1, min(240, len(candidates)), dtype=int)]
                normals_source = source.compute_normals(point_normals=True, cell_normals=False, inplace=False)
                normals = np.asarray(normals_source.point_data.get("Normals", np.zeros_like(points)), dtype=float)
                cloud = self._pv.PolyData(points[selected] + 0.0015 * normals[selected])
                selected_vector = vector[selected]
                selected_magnitude = np.linalg.norm(selected_vector, axis=1)
                cloud["wall_shear_direction"] = selected_vector / np.maximum(selected_magnitude[:, None], 1e-12)
                cloud["wall_shear_pa"] = selected_magnitude
                arrow = self._pv.Arrow(tip_length=0.50, tip_radius=0.18, shaft_radius=0.060)
                glyphs = cloud.glyph(orient="wall_shear_direction", scale=False, factor=0.034, geom=arrow)
                self._plotter.add_mesh(
                    glyphs, scalars="wall_shear_pa", cmap="inferno", clim=clim, opacity=0.88,
                    name="cfd-wall-shear", show_scalar_bar=False,
                    reset_camera=False,
                )
                contours = source.contour(isosurfaces=8, scalars="wall_shear_pa")
                if contours.n_points:
                    self._plotter.add_mesh(
                        contours, color="#27384a", opacity=0.46, line_width=1.0,
                        name="cfd-wall-shear-contours", show_scalar_bar=False, reset_camera=False,
                    )
                self._force_actor_names["friction"] = "cfd-wall-shear"
        except (OSError, KeyError, ValueError, TypeError):
            return

    def _build_real_streamlines(self, field: object) -> None:
        """Use VTK's vector integrator; never substitute decorative paths."""
        for name in self._streamline_names:
            self._plotter.remove_actor(name, render=False)
        self._streamline_names.clear()
        if "velocity" not in self._cfd_available_fields:
            return
        try:
            lines = self._integrated_pathlines(field, "velocity_mps", max_count=34, compact=True)
            if lines is not None and lines.n_points:
                lines["stream_velocity_mps"] = np.linalg.norm(np.asarray(lines["U"]), axis=1)
                clim = robust_scalar_range(lines["stream_velocity_mps"], lower=1.0, upper=99.0)
                tubes = lines.tube(radius=0.0025, n_sides=7)
                self._plotter.add_mesh(
                    tubes, scalars="stream_velocity_mps", cmap="turbo", clim=clim, opacity=0.86,
                    smooth_shading=True, name="cfd-streamlines", show_scalar_bar=True,
                    scalar_bar_args=self._scalar_bar("Velocidad (m/s)"),
                    reset_camera=False,
                )
                self._streamline_names.append("cfd-streamlines")
                self._add_pathline_arrows(
                    lines, scalar="stream_velocity_mps", clim=clim, cmap="turbo",
                    actor_name="cfd-streamline-arrows",
                )
                self._streamline_names.append("cfd-streamline-arrows")
                self._render_velocity_plane(field, clim)
                self._plotter.add_text(
                    f"LÍNEAS DE CORRIENTE OPENFOAM\n{self._trajectory_count(lines)} trayectorias · "
                    f"{clim[0]:.3g}–{clim[1]:.3g} m/s\nSembradas aguas arriba del cohete",
                    name="cfd-mode-info", position="upper_left", font_size=9, color="#17212b",
                )
        except Exception:
            return

    def _render_scalar_pathlines(
        self, field: object, *, scalar: str, title: str, unit: str, cmap: str, actor_name: str,
        log_scale: bool = False,
    ) -> None:
        """Render a selected CFD magnitude only as real, ranked flow trajectories."""
        try:
            is_vortex = scalar == "vorticity_1ps"
            max_count = 12 if is_vortex else 72
            lines = self._integrated_pathlines(
                field, scalar, max_count=max_count, compact=True, feature_seeded=True,
            )
            if lines is None or not lines.n_points:
                return
            values = np.asarray(lines.point_data[scalar], dtype=float)
            clim = robust_scalar_range(values, lower=5.0, upper=95.0)
            if log_scale:
                positive = values[np.isfinite(values) & (values > 0.0)]
                if not len(positive):
                    return
                clim = (
                    max(float(np.nanpercentile(positive, 5.0)), 1e-12),
                    max(float(np.nanpercentile(positive, 97.0)), 1e-11),
                )
            tubes = lines.tube(radius=0.0036 if is_vortex else 0.0024, n_sides=9)
            self._plotter.add_mesh(
                tubes, scalars=scalar, cmap=cmap, clim=clim, log_scale=log_scale,
                opacity=0.90 if is_vortex else 0.96, smooth_shading=True,
                ambient=0.22 if is_vortex else 0.0, specular=0.48 if is_vortex else 0.0,
                specular_power=24 if is_vortex else 1.0, name=actor_name, show_scalar_bar=True,
                scalar_bar_args=self._scalar_bar(f"{title} ({unit})"), reset_camera=False,
            )
            self._vortex_names.append(actor_name)
            arrow_name = f"{actor_name}-arrows"
            self._add_pathline_arrows(
                lines, scalar=scalar, clim=clim, cmap=cmap,
                actor_name=arrow_name, log_scale=log_scale,
                max_glyphs=16 if is_vortex else None, arrow_scale=0.031 if is_vortex else None,
            )
            self._vortex_names.append(arrow_name)
            self._plotter.add_text(
                f"{'NÚCLEOS VORTICALES' if is_vortex else title.upper()} · OPENFOAM\n"
                f"{self._trajectory_count(lines)} trayectorias seleccionadas · {clim[0]:.3g}–{clim[1]:.3g} {unit}\n"
                "Sin envolventes ni volúmenes decorativos",
                name="cfd-mode-info", position="upper_left", font_size=9, color="#17212b",
            )
        except Exception:
            return

    def _add_real_vorticity_surface(self, field: object) -> None:
        """Show local OpenFOAM vorticity as directional rotation rings."""
        if "vorticity" in self._cfd_available_fields:
            self._add_vortex_rotation_rings(field)

    def _add_turbulence_pathlines(self, field: object) -> None:
        if "turbulence" in self._cfd_available_fields:
            self._render_scalar_pathlines(
                field, scalar="turbulence_intensity_pct", title="Intensidad turbulenta", unit="%",
                cmap="turbo", actor_name="cfd-turbulence-lines",
            )

    def _add_openfoam_force_vectors(self, result: object) -> None:
        for name in self._force_names:
            self._plotter.remove_actor(name, render=False)
        self._force_names.clear()
        self._force_actor_names.clear()
        rocket_force = np.asarray(result.force_n, dtype=float)
        recovery_force = np.asarray(getattr(result, "recovery_force_n", (0.0, 0.0, 0.0)), dtype=float)
        projected = aerodynamic_force_vectors(
            rocket_force + recovery_force,
            getattr(result, "inlet_velocity_body_mps", (1.0, 0.0, 0.0)),
        )
        components = [
            ("drag", "Arrastre", "#d62828", projected["drag"]),
            ("lift", "Sustentación", "#218c4a", projected["lift"]),
            ("side", "Fuerza lateral", "#1769aa", projected["side"]),
        ]
        viscous = getattr(result, "viscous_force_n", None)
        if viscous is not None:
            vector = np.asarray(viscous, dtype=float)
            if float(np.linalg.norm(vector)) > 1e-12:
                components.append(("friction", "Fricción viscosa", "#f59e0b", vector))
        maximum = max((float(np.linalg.norm(vector)) for *_rest, vector in components), default=0.0)
        legend = [
            "CARGAS AERODINÁMICAS DEL SISTEMA (N)"
            if float(np.linalg.norm(recovery_force)) > 1e-12
            else "FUERZAS SOBRE EL COHETE · CFD/OpenFOAM (N)"
        ]
        for index, (layer, label, color, vector) in enumerate(components):
            magnitude = float(np.linalg.norm(vector))
            if magnitude <= 1e-12:
                continue
            origin = np.asarray(getattr(result, "center_of_gravity_body_m", (0.0, 0.0, 0.0)), dtype=float)
            arrow = self._pv.Arrow(start=origin, direction=vector / magnitude,
                                   scale=0.10 + 0.42 * magnitude / maximum,
                                   tip_length=0.22, tip_radius=0.065)
            name = f"openfoam-force-{index}"
            self._plotter.add_mesh(arrow, color=color, name=name, reset_camera=False)
            self._force_names.append(name)
            self._force_actor_names[layer] = name
            legend.append(f"{label}: {magnitude:.3g} N")
        self._plotter.add_text("\n".join(legend), name="force-legend", position="upper_right", font_size=8, color="#202b33")
        self._apply_layer_visibility()

    def _add_openfoam_moment(self, frame: object) -> None:
        """Show the integrated moment with an oriented arc, axis and arrowhead."""
        if not self._plotter or not self._pv:
            return
        self._plotter.remove_actor("cfd-moment", render=False)
        moment = np.asarray(_frame_value(frame, "moment_nm", (0.0, 0.0, 0.0)), dtype=float)
        magnitude = float(np.linalg.norm(moment))
        if magnitude <= 1e-12:
            return
        try:
            axis = moment / magnitude
            origin = np.asarray(_frame_value(frame, "center_of_gravity_body_m", (0.0, 0.0, 0.0)), dtype=float)
            arc = self._pv.CircularArcFromNormal(
                normal=axis, polar=np.array((0.0, 0.28, 0.0)), angle=275.0,
                center=origin, resolution=72,
            )
            tube = arc.tube(radius=0.009, n_sides=10)
            tangent = np.asarray(arc.points[-1], dtype=float) - np.asarray(arc.points[-3], dtype=float)
            tangent /= max(float(np.linalg.norm(tangent)), 1e-12)
            tip = self._pv.Arrow(
                start=np.asarray(arc.points[-1], dtype=float) - tangent * 0.045,
                direction=tangent, scale=0.13, tip_length=0.48, tip_radius=0.12, shaft_radius=0.025,
            )
            axis_arrow = self._pv.Arrow(
                start=origin, direction=axis, scale=0.24,
                tip_length=0.30, tip_radius=0.09, shaft_radius=0.020,
            )
            self._plotter.add_mesh(tube, color="#c850ff", name="cfd-moment", reset_camera=False)
            self._plotter.add_mesh(tip, color="#f08cff", name="cfd-moment-tip", reset_camera=False)
            self._plotter.add_mesh(axis_arrow, color="#8e35c9", name="cfd-moment-axis", reset_camera=False)
            self._force_names.extend(("cfd-moment", "cfd-moment-tip", "cfd-moment-axis"))
            self._force_actor_names["vortices"] = "cfd-moment"
        except (TypeError, ValueError):
            return

    def _add_selected_force_vector(self, frame: object, layer: str) -> None:
        """Draw one integrated OpenFOAM load from the vehicle centre of gravity."""
        force = np.asarray(_frame_value(frame, "force_n", (0.0, 0.0, 0.0)), dtype=float)
        recovery = np.asarray(_frame_value(frame, "recovery_force_n", (0.0, 0.0, 0.0)), dtype=float)
        system_force = force + recovery
        projected = aerodynamic_force_vectors(
            system_force, _frame_value(frame, "inlet_velocity_body_mps", (1.0, 0.0, 0.0)),
        )
        viscous = _frame_value(frame, "viscous_force_n")
        definitions = {
            "drag": ("Arrastre", "#ff334c", projected["drag"]),
            "lift": ("Sustentación", "#38e56f", projected["lift"]),
            "side": ("Fuerza lateral", "#35a7ff", projected["side"]),
            "friction": ("Fricción viscosa", "#ff9f1c", np.asarray(viscous if viscous is not None else force, dtype=float)),
        }
        if layer not in definitions:
            return
        label, color, vector = definitions[layer]
        magnitude = float(np.linalg.norm(vector))
        if magnitude > 1e-12:
            direction = vector / magnitude
            total = max(float(np.linalg.norm(system_force)), magnitude, 1e-12)
            # A longitudinal load must extend beyond the 0.451 m half-body;
            # otherwise the opaque rocket hides the complete arrow.
            visual_length = 0.60 + 0.20 * min(magnitude / total, 1.0)
            arrow = self._pv.Arrow(
                start=np.asarray(_frame_value(frame, "center_of_gravity_body_m", (0.0, 0.0, 0.0)), dtype=float),
                direction=direction, scale=visual_length,
                tip_length=0.24, tip_radius=0.075, shaft_radius=0.022,
            )
            name = f"openfoam-selected-{layer}"
            self._plotter.add_mesh(arrow, color=color, name=name, reset_camera=False)
            self._force_names.append(name)
            self._force_actor_names[layer] = name
        source_note = (
            "Sistema = cohete OpenFOAM + recuperación q·CdS 6-DoF"
            if float(np.linalg.norm(recovery)) > 1e-12 and layer != "friction"
            else "Superficie del cohete integrada por OpenFOAM"
        )
        self._plotter.add_text(
            f"{label.upper()} · RESULTADO INTEGRADO\n|F| = {magnitude:.5g} N\n"
            f"Vector = ({vector[0]:+.4g}, {vector[1]:+.4g}, {vector[2]:+.4g}) N\n"
            f"{source_note}\nOrigen de la flecha: centro de gravedad",
            name="cfd-mode-info", position="upper_left", font_size=9, color="#17212b",
        )

    def _clear_active_cfd_visual(self) -> None:
        """Release the previous field representation before creating another."""
        if not self._plotter:
            return
        names = {
            *self._streamline_names, *self._vortex_names, *self._force_names,
            *self._force_actor_names.values(), "cfd-velocity-glyphs", "cfd-streamlines",
            "cfd-velocity-plane", "cfd-vorticity-surface", "cfd-pressure-surface",
            "cfd-vorticity-lines", "cfd-vortex-rings", "cfd-vortex-ring-arrows", "cfd-turbulence-lines", "cfd-wall-shear",
            "cfd-wall-shear-surface", "cfd-wall-shear-contours", "cfd-moment", "cfd-moment-tip",
            "cfd-moment-axis", "force-legend", "cfd-mode-info", "preview-notice", "cfd-caption",
            "openfoam-selected-drag",
            "openfoam-selected-lift", "openfoam-selected-side", "openfoam-selected-friction",
        }
        for name in names:
            self._plotter.remove_actor(name, render=False)
        for title in (
            "Velocidad (m/s)", "Presión manométrica (Pa)", "Vorticidad (1/s)",
            "Intensidad turbulenta (%)", "Esfuerzo cortante (Pa)",
        ):
            try:
                self._plotter.remove_scalar_bar(title, render=False)
            except (KeyError, ValueError):
                pass
        self._streamline_names.clear(); self._vortex_names.clear(); self._force_names.clear()
        self._force_actor_names.clear(); self._cfd_dataset = None
        gc.collect()

    def _set_visual_mode_background(self) -> None:
        """Use a soft neutral gradient without sacrificing CFD contrast."""
        self._plotter.set_background("#f3f5f7", top="#cfd5db")

    def _discover_cfd_fields(self, field: object) -> None:
        arrays = set(field.point_data)
        if "U" in arrays:
            vector = np.asarray(field.point_data["U"])
            if vector.ndim == 2 and vector.shape[1] == 3:
                field.point_data["velocity_mps"] = np.linalg.norm(vector, axis=1)
                self._cfd_available_fields["velocity"] = "velocity_mps"
        pressure = next((name for name in ("p", "p_rgh") if name in arrays), None)
        if pressure:
            field.point_data["pressure_pa"] = np.asarray(field.point_data[pressure]) * float(
                getattr(self._cfd_result, "air_density_kg_m3", 1.225)
            )
            self._cfd_available_fields["pressure"] = "pressure_pa"
        vortex = next((name for name in ("vorticity", "curlU") if name in arrays), None)
        if vortex:
            values = np.asarray(field.point_data[vortex])
            field.point_data["vorticity_1ps"] = np.linalg.norm(values, axis=1) if values.ndim == 2 else values
            self._cfd_available_fields["vorticity"] = "vorticity_1ps"
        if "Q" in arrays:
            self._cfd_available_fields["q_criterion"] = "Q"
        if "k" in arrays and "U" in arrays:
            k_values = np.maximum(np.asarray(field.point_data["k"], dtype=float), 0.0)
            speed = np.linalg.norm(np.asarray(field.point_data["U"], dtype=float), axis=1)
            field.point_data["turbulence_intensity_pct"] = (
                100.0 * np.sqrt((2.0 / 3.0) * k_values) / np.maximum(speed, 0.25)
            )
            self._cfd_available_fields["turbulence"] = "turbulence_intensity_pct"

    def _render_active_cfd_mode(self, field: object | None, frame: object) -> None:
        mode = self._cfd_layer
        if mode == "velocity" and field is not None:
            self._build_real_streamlines(field)
        elif mode == "pressure":
            self._render_surface_fields(frame)
        elif mode == "vorticity" and field is not None:
            self._add_real_vorticity_surface(field)
        elif mode == "turbulence" and field is not None:
            self._add_turbulence_pathlines(field)
        elif mode in {"drag", "lift", "side"}:
            self._add_selected_force_vector(frame, mode)
        elif mode == "friction":
            self._render_surface_fields(frame)
            self._add_selected_force_vector(frame, mode)
        elif mode == "moment":
            self._add_openfoam_moment(frame)
            moment = np.asarray(_frame_value(frame, "moment_nm", (0.0, 0.0, 0.0)), dtype=float)
            magnitude = float(np.linalg.norm(moment))
            self._plotter.add_text(
                f"MOMENTO AERODINÁMICO INTEGRADO\n|M| = {magnitude:.5g} N·m\n"
                f"Vector = ({moment[0]:+.4g}, {moment[1]:+.4g}, {moment[2]:+.4g}) N·m\n"
                "Arco = sentido · eje = orientación",
                name="cfd-mode-info", position="upper_left", font_size=9, color="#17212b",
            )

    def set_cfd_frame(self, index: int, *, force: bool = False) -> tuple[float, float, float, float] | None:
        """Select one discrete OpenFOAM state; no field interpolation is used."""
        if not self._plotter or not self._pv or not self._cfd_frames:
            return None
        index = min(max(0, int(index)), len(self._cfd_frames) - 1)
        if not force and index == self._cfd_frame_index:
            frame = self._cfd_frames[index]
            return tuple(float(value) for value in _frame_value(frame, "canard_deg", self._canards))
        frame = self._cfd_frames[index]
        vtk_path = _frame_value(frame, "vtk_path")
        if not vtk_path or not Path(vtk_path).is_file():
            return None
        self._clear_active_cfd_visual()
        self._set_visual_mode_background()
        self._cfd_frame_index = index
        field = None
        try:
            # Forces, moment and surface pressure do not need the 40–50 MB
            # internal volume.  Read it only for velocity or vorticity.
            if self._cfd_layer in {"velocity", "vorticity", "turbulence"}:
                field = self._pv.read(vtk_path)
                point_arrays = set(field.point_data)
                required = {
                    "velocity": "U", "vorticity": "vorticity", "turbulence": "k",
                }[self._cfd_layer]
                if required not in point_arrays and required in set(field.cell_data):
                    field = field.cell_data_to_point_data(pass_cell_data=False)
                self._discover_cfd_fields(field)
            self._render_active_cfd_mode(field, frame)
            self.set_canard_deflections(tuple(float(value) for value in _frame_value(frame, "canard_deg", self._canards)))
            self._cfd_dataset = None
            field = None
            gc.collect()
            self._render_scene()
        except Exception as exc:
            self._cfd_dataset = None
            field = None
            gc.collect()
            self._plotter.add_text(f"No se pudo mostrar el estado VTK: {exc}", name="cfd-result", position="lower_left", font_size=9, color="#8b3a1d")
            return None
        return tuple(float(value) for value in _frame_value(frame, "canard_deg", self._canards))

    def show_cfd_result(self, result: object) -> None:
        """Render only fields exported by a completed OpenFOAM case."""
        if not self._plotter or not self._pv:
            return
        self._clear_result_actors()
        # Preview labels and its wind arrow are intentionally illustrative;
        # remove them before presenting the OpenFOAM post-processing scene.
        for name in (*self._preview_names, "preview-notice", "cfd-caption"):
            self._plotter.remove_actor(name, render=False)
        self._preview_names.clear()
        if getattr(result, "backend", "") != "OpenFOAM" or not bool(getattr(result, "converged", False)):
            self._plotter.add_text(
                "RESULTADO NO VALIDADO — no se habilitan campos hasta demostrar convergencia y calidad de malla.",
                name="cfd-result", position="lower_left", font_size=9, color="#8b3a1d",
            )
            self._render_scene()
            return
        vtk_path = getattr(result, "vtk_path", None)
        if not vtk_path or not Path(vtk_path).is_file():
            self._plotter.add_text(
                "CFD/OpenFOAM terminado, pero foamToVTK no exportó un campo legible.",
                name="cfd-result", position="lower_left", font_size=9, color="#8b3a1d",
            )
            self._render_scene()
            return
        try:
            self._cfd_result = result
            # Start every newly loaded snapshot in the bounded streamline
            # view. This also discovers which volume arrays are available.
            self._cfd_layer = "velocity"
            frames = tuple(_normalise_cfd_frame(frame) for frame in getattr(result, "frames", ()))
            if not frames:
                # Backward-compatible stationary result: still an actual VTK,
                # represented as precisely one discrete CFD frame.
                frames = (SimpleNamespace(
                    time_s=0.0, canard_deg=self._canards, vtk_path=vtk_path, surface_vtk_path=None,
                    force_n=result.force_n, moment_nm=result.moment_nm,
                    pressure_force_n=getattr(result, "pressure_force_n", None),
                    viscous_force_n=getattr(result, "viscous_force_n", None),
                    inlet_velocity_body_mps=getattr(result, "inlet_velocity_body_mps", (1.0, 0.0, 0.0)),
                    recovery_force_n=getattr(result, "recovery_force_n", (0.0, 0.0, 0.0)),
                    center_of_gravity_body_m=getattr(result, "center_of_gravity_body_m", (0.0, 0.0, 0.0)),
                ),)
            self._cfd_frames = frames
            self._plotter.add_text(
                "CFD DETALLADO / OpenFOAM — campos 3D y cargas proceden únicamente de VTK y fuerzas exportados.",
                name="cfd-result", position="lower_left", font_size=9, color="#17212b",
            )
            # Keep the engineering camera focused on the vehicle instead of
            # fitting the entire 11 m tunnel and making the rocket disappear.
            self.set_camera_preset("isometric")
            self.set_cfd_frame(0, force=True)
        except Exception as exc:
            self._plotter.add_text(
                f"No se pudo mostrar el VTK de OpenFOAM: {exc}", name="cfd-result",
                position="lower_left", font_size=9, color="#8b3a1d",
            )
        self._render_scene()
