    @staticmethod
    def _basis(direction: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
        helper = np.array((0.0, 0.0, 1.0))
        if abs(float(np.dot(direction, helper))) > 0.88:
            helper = np.array((1.0, 0.0, 0.0))
        first = np.cross(direction, helper)
        first /= max(float(np.linalg.norm(first)), 1e-9)
        second = np.cross(direction, first)
        second /= max(float(np.linalg.norm(second)), 1e-9)
        return first, second

    def _build_flow(self) -> None:
        if not self._plotter or not self._pv:
            return
        for name in self._flow_names:
            self._plotter.remove_actor(name, render=False)
        self._flow_names.clear()
        self._streamline_names.clear()
        self._vortex_names.clear()
        self._flow_paths.clear()
        self._vortex_meshes.clear()
        self._vortex_actors.clear()
        self._particle_mesh = None
        self._rain_mesh = None
        for title in ("Velocidad (m/s)", "Vorticidad (1/s)"):
            try:
                self._plotter.remove_scalar_bar(title, render=False)
            except (KeyError, ValueError):
                pass
        direction = flow_direction(self._alpha_deg, self._beta_deg)
        basis_u, basis_v = self._basis(direction)
        rng = np.random.default_rng(20260730)
        speed_scale = max(self._speed_mps, 0.2)
        seed_count = 76
        for index in range(seed_count):
            radius = math.sqrt((index + 0.7) / seed_count) * 1.04
            theta = index * 2.399963229728653
            radial = basis_u * (radius * math.cos(theta)) + basis_v * (radius * math.sin(theta))
            points: list[np.ndarray] = []
            scalar: list[float] = []
            phase = rng.uniform(0.0, 2.0 * math.pi)
            for step in range(42):
                t = step / 41.0
                axial = -1.85 + 3.70 * t
                base = direction * axial + radial
                near_body = math.exp(-((axial + 0.02) / 0.48) ** 2)
                radial_norm = max(float(np.linalg.norm(radial)), 0.08)
                avoidance = radial / radial_norm * near_body * (0.17 / (0.30 + radial_norm))
                wake = max(0.0, min(1.0, (axial - 0.05) / 1.25))
                swirl_strength = wake * (0.035 + 0.004 * sum(abs(value) for value in self._canards))
                swirl = (
                    basis_u * math.cos(phase + t * 16.0) +
                    basis_v * math.sin(phase + t * 16.0)
                ) * swirl_strength
                points.append(base + avoidance + swirl)
                local_speed = speed_scale * (0.72 + 0.43 * t + 0.20 * near_body)
                scalar.append(local_speed)
            path = np.asarray(points)
            self._flow_paths.append(path)
            line = self._pv.Spline(path, n_points=84)
            line.point_data["velocity_mps"] = np.linspace(min(scalar), max(scalar), line.n_points)
            name = f"streamline-{index}"
            self._plotter.add_mesh(
                line, scalars="velocity_mps", cmap="turbo", clim=(0.0, max(1.0, speed_scale * 1.4)),
                line_width=2.0, opacity=0.72, render_lines_as_tubes=True, name=name,
                show_scalar_bar=index == 0,
                scalar_bar_args={"title": "Velocidad (m/s)", "vertical": True, "position_x": 0.87, "position_y": 0.12, "height": 0.45},
                reset_camera=False,
            )
            self._flow_names.append(name)
            self._streamline_names.append(name)
        self._add_vortices(direction, basis_u, basis_v)
        particle_points = np.vstack([path[0] for path in self._flow_paths for _ in range(2)])
        particle_speed = np.full(len(particle_points), speed_scale)
        self._particle_mesh = self._pv.PolyData(particle_points)
        self._particle_mesh.point_data["velocity_mps"] = particle_speed
        name = "flow-particles"
        self._plotter.add_mesh(
            self._particle_mesh, scalars="velocity_mps", cmap="turbo",
            clim=(0.0, max(1.0, speed_scale * 1.4)), point_size=7,
            render_points_as_spheres=True, show_scalar_bar=False, name=name, reset_camera=False,
        )
        self._flow_names.append(name)
        if self._rain_rate_mm_h > 0.0:
            count = min(180, max(28, int(self._rain_rate_mm_h * 8)))
            rain_points = rng.uniform((-1.15, -1.15, -1.8), (1.15, 1.15, 1.8), (count, 3))
            self._rain_mesh = self._pv.PolyData(rain_points)
            self._rain_mesh.point_data["impact"] = np.linspace(0.0, 1.0, count)
            name = "rain-particles"
            self._plotter.add_mesh(
                self._rain_mesh, scalars="impact", cmap="winter", point_size=5,
                render_points_as_spheres=True, show_scalar_bar=False, opacity=0.8,
                name=name, reset_camera=False,
            )
            self._flow_names.append(name)
        self._apply_layer_visibility()

    def _add_vortices(self, direction: np.ndarray, basis_u: np.ndarray, basis_v: np.ndarray) -> None:
        if not self._plotter or not self._pv:
            return
        for index in range(8):
            points, values = self._vortex_points(index, direction, basis_u, basis_v, 100)
            vortex = self._pv.Spline(points, n_points=100)
            vortex.point_data["vorticity_s"] = values
            name = f"vortex-{index}"
            actor = self._plotter.add_mesh(
                vortex, scalars="vorticity_s", cmap="plasma", line_width=3.0, opacity=0.86,
                clim=(0.0, max(1.0, float(values.max()))),
                render_lines_as_tubes=True, show_scalar_bar=index == 0,
                scalar_bar_args={"title": "Vorticidad (1/s)", "vertical": True, "position_x": 0.03, "position_y": 0.12, "height": 0.35},
                name=name, reset_camera=False,
            )
            self._flow_names.append(name)
            self._vortex_names.append(name)
            self._vortex_meshes.append(vortex)
            self._vortex_actors.append(actor)

    def _vortex_points(
        self, index: int, direction: np.ndarray, basis_u: np.ndarray, basis_v: np.ndarray, count: int,
    ) -> tuple[np.ndarray, np.ndarray]:
        canard_strength = 0.06 + 0.006 * sum(abs(value) for value in self._canards)
        points: list[np.ndarray] = []
        values: list[float] = []
        phase = index * math.pi / 4.0
        for step in range(count):
            t = step / max(1, count - 1)
            axial = 0.08 + 1.55 * t
            radius = canard_strength * (0.8 + 0.75 * t)
            angle = phase + t * (5.5 * math.pi)
            points.append(direction * axial + basis_u * radius * math.cos(angle) + basis_v * radius * math.sin(angle))
            values.append(self._speed_mps * radius * (1.0 + t))
        return np.asarray(points), np.asarray(values)

    def _update_vortices(self) -> None:
        if not self._vortex_meshes:
            return
        direction = flow_direction(self._alpha_deg, self._beta_deg)
        basis_u, basis_v = self._basis(direction)
        for index, (mesh, actor) in enumerate(zip(self._vortex_meshes, self._vortex_actors)):
            points, values = self._vortex_points(index, direction, basis_u, basis_v, mesh.n_points)
            mesh.points = points
            mesh.point_data["vorticity_s"] = values
            actor.mapper.scalar_range = (0.0, max(1.0, float(values.max())))
            mesh.Modified()

