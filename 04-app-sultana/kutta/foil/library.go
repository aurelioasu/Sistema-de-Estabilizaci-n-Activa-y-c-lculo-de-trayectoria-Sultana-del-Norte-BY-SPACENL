package foil

import "strings"

// Library returns bundled coordinate profiles whose NACA designations are not
// covered by the analytical 4- and 5-digit generators. Coordinates use the
// standard Selig order and are kept locally so the desktop tunnel is offline.
func Library(code string) ([]Point, bool) {
	var data string
	switch normalizeCode(code) {
	case "661212":
		data = naca661212DAT
	case "747a315":
		data = naca747a315DAT
	default:
		return nil, false
	}
	outline, err := ParseDAT([]byte(data))
	return outline, err == nil
}

func normalizeCode(code string) string {
	code = strings.ToLower(strings.TrimSpace(code))
	code = strings.NewReplacer("-", "", "(", "", ")", "", " ", "").Replace(code)
	return code
}

